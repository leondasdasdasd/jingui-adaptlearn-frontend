/**
 *
 * @param question
 */
function repairTextCompleteVisualWords(question) {
  const patch = GRADE7_TEXT_COMPLETE_VISUAL_WORD_REPAIRS.get(question?.id);
  if (!patch) return question;
  const { optionTexts, ...questionPatch } = patch;
  const options = optionTexts
    ? (question.options || []).map((option) => ({
        ...option,
        text: patch.optionTexts[option.id] || option.text,
      }))
    : question.options;
  return { ...question, ...questionPatch, options, platformQuestion: null };
}

/**
 *
 * @param question
 */
export function repairGrade7QuestionContract(question) {
  const patch = GRADE7_QUESTION_CONTRACT_REPAIRS.get(question?.id);
  return repairTextCompleteVisualWords(
    patch ? { ...question, ...patch } : question,
  );
}
